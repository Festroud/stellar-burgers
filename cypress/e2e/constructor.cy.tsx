/// <reference types="cypress" />

describe('Конструктор бургеров', () => {
  beforeEach(() => {
    // перехваты API перед каждым тестом
    cy.setupApiIntercepts();
    
    // Переход на главную страницу
    cy.visit('/');
    
    // Ждём загрузки ингредиентов
    cy.wait('@getIngredients');
  });

  describe('Добавление ингредиентов в конструктор', () => {
    it('должно добавлять булку в конструктор при клике на кнопку', () => {
      // Проверяем, что ингредиенты загрузились
      cy.contains('Краторная булка N-200i').should('be.visible');
      
      // Ищем любой элемент с текстом булки, затем кнопку добавить
      cy.contains('Краторная булка N-200i')
        .closest('li') // идем к li элементу (контейнер ингредиента)
        .contains('Добавить')
        .click();

      // Проверяем, что булка появилась в конструкторе (верхняя и нижняя)
      cy.contains('Краторная булка N-200i (верх)').should('be.visible');
      cy.contains('Краторная булка N-200i (низ)').should('be.visible');
    });

    it('должно добавлять начинки в конструктор при клике на кнопку', () => {
      // Добавляем булку сначала
      cy.contains('Краторная булка N-200i')
        .closest('li')
        .contains('Добавить')
        .click();

      // Находим и добавляем основную начинку (говяжий метеорит)
      cy.contains('Говяжий метеорит')
        .closest('li')
        .contains('Добавить')
        .click();

      // Добавляем соус
      cy.contains('Соус Spicy-X')
        .closest('li')
        .contains('Добавить')
        .click();

      // Проверяем, что начинки добавились (ищем в любом месте страницы)
      cy.get('body').should('contain.text', 'Говяжий метеорит');
      cy.get('body').should('contain.text', 'Соус Spicy-X');
    });
  });

  describe('Модальные окна ингредиентов', () => {
    it('должно открывать модальное окно при клике на ингредиент', () => {
      // Кликаем по ингредиенту (по названию, обернутому в ссылку)
      cy.contains('Краторная булка N-200i').click();

      // Проверяем, что модальное окно открылось
      cy.contains('Детали ингридиента').should('be.visible');
      
      // Проверяем, что в модальном окне отображаются данные конкретного ингредиента
      cy.contains('Краторная булка N-200i').should('be.visible');
      cy.contains('420').should('be.visible'); // Калории
    });

    it('должно закрывать модальное окно при клике на крестик', () => {
      // Открываем модальное окно
      cy.contains('Краторная булка N-200i').click();

      // Проверяем, что модальное окно открыто
      cy.contains('Детали ингридиента').should('be.visible');

      // Кликаем на крестик (ищем любую кнопку в модалке)
      cy.contains('Детали ингридиента')
        .parent()
        .parent()
        .find('button')
        .click();

      // Проверяем, что модальное окно закрылось
      cy.contains('Детали ингридиента').should('not.exist');
    });

    it('должно закрывать модальное окно при клике на оверлей', () => {
      // Открываем модальное окно
      cy.contains('Краторная булка N-200i').click();

      // Проверяем, что модальное окно открыто
      cy.contains('Детали ингридиента').should('be.visible');

      // Кликаем на оверлей (область вне модального окна)
      cy.get('body').click(0, 0);

      // Проверяем, что модальное окно закрылось
      cy.contains('Детали ингридиента').should('not.exist');
    });

    it('должно отображать корректные данные ингредиента в модальном окне', () => {
      // Кликаем на конкретный ингредиент
      cy.contains('Говяжий метеорит').click();

      // Проверяем, что модальное окно открылось
      cy.contains('Детали ингридиента').should('be.visible');

      // Проверяем корректность данных в модальном окне
      cy.contains('Говяжий метеорит (отбивная)').should('be.visible');
      // Проверяем пищевую ценность
      cy.contains('800').should('be.visible'); // Белки
      cy.contains('300').should('be.visible'); // Углеводы  
      cy.contains('2674').should('be.visible'); // Калории
    });
  });

  describe('Создание заказа', () => {
    it('должно создавать заказ и показывать правильный номер заказа', () => {
      // Устанавливаем токены авторизации
      cy.setAuthTokens();

      // Собираем бургер: добавляем булку
      cy.contains('Краторная булка N-200i')
        .closest('li')
        .contains('Добавить')
        .click();

      // Добавляем начинку
      cy.contains('Говяжий метеорит')
        .closest('li')
        .contains('Добавить')
        .click();

      // Добавляем соус  
      cy.contains('Соус Spicy-X')
        .closest('li')
        .contains('Добавить')
        .click();

      // Кликаем на кнопку "Оформить заказ"  
      cy.contains('Оформить заказ').click();

      // Ждём что заказ начал обрабатываться - кнопка исчезла
      cy.get('body', { timeout: 10000 }).should('not.contain.text', 'Оформить заказ');
      
      // Ждём завершения создания заказа
      cy.wait(5000);

      // Закрываем модальное окно
      cy.get('body').type('{esc}');
      
      // Ждём обновления состояния
      cy.wait(2000);

      // Проверяем успешное создание заказа
      cy.get('body').then(($body) => {
        const bodyText = $body.text();
        const constructorCleared = bodyText.includes('Выберите булки');
        const orderProcessed = !bodyText.includes('Оформить заказ');
        
        expect(constructorCleared || orderProcessed).to.be.true;
      });

      // Очищаем токены после теста
      cy.clearAuthTokens();
    });

    it('должно перенаправлять на страницу логина для неавторизованных пользователей', () => {
      // НЕ устанавливаем токены авторизации

      // Собираем бургер (добавляем булку)
      cy.contains('Краторная булка N-200i')
        .closest('li')
        .contains('Добавить')
        .click();

      // Кликаем на кнопку "Оформить заказ"
      cy.contains('Оформить заказ').click();

      // Проверяем, что произошло перенаправление на страницу логина
      cy.url().should('include', '/login');
    });
  });
});
